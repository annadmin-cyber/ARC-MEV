// Regenerates test/math/fixtures.ts from the Foundry reference-vector tests.
// Usage (from the repo root):
//   (cd contracts && forge test --match-path 'test/vectors/*' -vv) | node test/math/gen-fixtures.mjs > test/math/fixtures.ts
import { readFileSync } from 'node:fs'

const lines = readFileSync(0, 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l.startsWith('V|'))
  .map((l) => l.slice(2).split('|'))

const big = (v) => `${v}n`
const num = (v) => String(Number(v))
const bool = (v) => (v === '1' ? 'true' : 'false')
const str = (v) => JSON.stringify(v)
const tsType = new Map([[big, 'bigint'], [num, 'number'], [bool, 'boolean'], [str, 'string']])

const shapes = {
  sqrtAtTick: { out: 'sqrtAtTick', fields: [['tick', num], ['sqrtPriceX96', big]] },
  tickAtSqrt: { out: 'tickAtSqrt', fields: [['sqrtPriceX96', big], ['tick', num]] },
  step: {
    out: 'swapSteps',
    fields: [
      ['sqrtPriceCurrentX96', big], ['sqrtPriceTargetX96', big], ['liquidity', big], ['amountRemaining', big],
      ['feePips', big], ['sqrtPriceNextX96', big], ['amountIn', big], ['amountOut', big], ['feeAmount', big],
    ],
  },
  amount0: { out: 'amount0Deltas', fields: [['a', big], ['b', big], ['liquidity', big], ['roundUp', bool], ['result', big]] },
  amount1: { out: 'amount1Deltas', fields: [['a', big], ['b', big], ['liquidity', big], ['roundUp', bool], ['result', big]] },
  nextFromInput: { out: 'nextFromInput', fields: [['sqrtPX96', big], ['liquidity', big], ['amount', big], ['zeroForOne', bool], ['result', big]] },
  nextFromOutput: { out: 'nextFromOutput', fields: [['sqrtPX96', big], ['liquidity', big], ['amount', big], ['zeroForOne', bool], ['result', big]] },
  compress: { out: 'compressVectors', fields: [['tick', num], ['tickSpacing', num], ['compressed', num], ['wordPos', num], ['bitPos', num]] },
  swapFee: { out: 'swapFees', fields: [['protocolFee', num], ['lpFee', num], ['swapFee', big]] },
  pool: {
    out: 'simPools',
    fields: [['name', str], ['tickSpacing', num], ['sqrtPriceX96', big], ['tick', num], ['protocolFee', num], ['lpFee', num], ['liquidity', big]],
  },
  tick: { out: 'simTicks', fields: [['pool', str], ['tick', num], ['liquidityGross', big], ['liquidityNet', big]] },
  swap: {
    out: 'simSwaps',
    fields: [
      ['pool', str], ['zeroForOne', bool], ['amountSpecified', big], ['sqrtPriceX96After', big], ['tickAfter', num],
      ['liquidityAfter', big], ['amount0', big], ['amount1', big],
    ],
  },
}

const groups = {}
const types = {}
for (const [kind, ...values] of lines) {
  const shape = shapes[kind]
  if (!shape) throw new Error(`unknown vector kind ${kind}`)
  if (values.length !== shape.fields.length) throw new Error(`bad arity for ${kind}: ${values.join('|')}`)
  const body = shape.fields.map(([name, fmt], i) => `${name}: ${fmt(values[i])}`).join(', ')
  types[shape.out] = shape.fields.map(([name, fmt]) => `${name}: ${tsType.get(fmt)}`).join('; ')
  ;(groups[shape.out] ??= []).push(`  { ${body} },`)
}

const out = [
  '// GENERATED by test/math/gen-fixtures.mjs from contracts/test/vectors/*.t.sol. Do not edit by hand.',
  '// Regenerate: (cd contracts && forge test --match-path \'test/vectors/*\' -vv) | node test/math/gen-fixtures.mjs > test/math/fixtures.ts',
  '',
]
for (const [name, rows] of Object.entries(groups)) {
  out.push(`export const ${name}: ReadonlyArray<{ ${types[name]} }> = [`, ...rows, ']', '')
}
process.stdout.write(out.join('\n'))
